namespace {

enum { ESuccess = 0, EFailUsage = 1, EFailCompile = 2, EFailLink = 3 };

/* What the tool prints, kept per call. A usage error ends the call as the tool's Error() ends the process (exit code 1). */
struct Io {
    std::string out, err;
    void printf_out(const char *fmt, ...) __attribute__((format(printf, 2, 3)))
    {
        va_list a; va_start(a, fmt); add(out, fmt, a); va_end(a);
    }
    void printf_err(const char *fmt, ...) __attribute__((format(printf, 2, 3)))
    {
        va_list a; va_start(a, fmt); add(err, fmt, a); va_end(a);
    }
    void puts_if_non_empty(const char *s) { if (s && s[0]) { out += s; out += '\n'; } }       /* PutsIfNonEmpty */
    void stderr_if_non_empty(const char *s) { if (s && s[0]) { err += s; err += '\n'; } }     /* StderrIfNonEmpty */
private:
    static void add(std::string &to, const char *fmt, va_list a)
    {
        va_list b; va_copy(b, a);
        int n = vsnprintf(nullptr, 0, fmt, b);
        va_end(b);
        if (n <= 0) return;
        size_t at = to.size();
        to.resize(at + (size_t)n + 1);
        vsnprintf(&to[at], (size_t)n + 1, fmt, a);
        to.resize(at + (size_t)n);
    }
};

struct Usage { };   /* thrown by error(): the tool's exit(EFailUsage) */

struct Args {
    const char *exe = "glslangValidator";
    bool preprocess = false, spv = false, vulkan = false, link = false, relaxed_rules = false, aml = false, amb = false, reflect = false, versions = false, quiet = false;
    const char *stage = nullptr, *binary = nullptr;
    std::vector<std::string> files;
    std::string command_line;   /* CommandLineArguments: argv[1..] joined by spaces (SpvOptions.commandLineArguments) */
};

[[noreturn]] void error(Io &io, const Args &a, const char *message, const char *detail = nullptr)   /* StandAlone.cpp Error() */
{
    io.printf_err("%s: Error: ", a.exe);
    if (detail) io.printf_err("%s: ", detail);
    io.printf_err("%s (use -h for usage)\n", message);
    throw Usage();
}

void parse(Io &io, Args &a, int argc, const char **argv)   /* ProcessArguments + FinalizeArguments, for the flags above */
{
    if (argc > 0 && argv[0]) a.exe = argv[0];
    for (int i = 1; i < argc; i++) {
        if (i > 1) a.command_line += ' ';
        a.command_line += argv[i] ? argv[i] : "";
    }
    for (int i = 1; i < argc; i++) {
        const char *s = argv[i];
        if (!s) continue;
        if (s[0] != '-') {
            size_t n = strlen(s);
            if (n > 5 && !strcmp(s + n - 5, ".conf")) error(io, a, "a resource limits file (.conf) is not supported by this build", s);   /* the tool's SetConfigFile */
            a.files.push_back(s);
            continue;
        }
        switch (s[1]) {
        case '-': {
            std::string w(s + 2);
            std::transform(w.begin(), w.end(), w.begin(), [](unsigned char c) { return (char)tolower(c); });
            if (w == "auto-map-bindings" || w == "auto-map-binding" || w == "amb") a.amb = true;
            else if (w == "auto-map-locations" || w == "aml") a.aml = true;
            else if (w == "version") a.versions = true;
            else if (w == "quiet") a.quiet = true;
            else error(io, a, "unrecognized command-line option", s);
            break;
        }
        case 'E': a.preprocess = true; break;
        case 'R': a.relaxed_rules = true; break;
        case 'S':
            if (i + 1 >= argc || !argv[i + 1]) error(io, a, "no <stage> specified for -S");
            a.stage = argv[++i];
            break;
        case 'V':
            a.spv = a.vulkan = a.link = true;   /* setVulkanSpv: client Vulkan 1.0 */
            if (s[2] && atoi(s + 2) != 100) error(io, a, "unknown client version for -V, should be 100");
            break;
        case 'l': a.link = true; break;
        case 'o':
            if (i + 1 >= argc || !argv[i + 1]) error(io, a, "no <file> provided for -o");
            a.binary = argv[++i];
            break;
        case 'q': a.reflect = true; break;
        case 'v': a.versions = true; break;
        default: error(io, a, "unrecognized command-line option (not in this build's glslangValidator subset)", s);
        }
    }
    if (a.preprocess) {
        if (a.link) error(io, a, "can't use -E when linking is selected");
        if (a.reflect) error(io, a, "reflection requires linking, which can't be used when -E when is selected");
    }
    if (a.reflect && !a.link) error(io, a, "reflection requires -l for linking");
    if (a.binary && !a.spv) error(io, a, "no binary generation requested (e.g., -V)");
}

EShLanguage stage_of(Io &io, const Args &a, const std::string &file)   /* FindLanguage: -S, else the file's (second) extension */
{
    std::string name;
    if (a.stage) name = a.stage;
    else {
        size_t e1 = file.find_last_of('.');
        if (e1 == std::string::npos) error(io, a, "no -S <stage> and no stage extension", file.c_str());
        std::string ext = file.substr(e1 + 1);
        if (ext == "glsl") {
            size_t e2 = e1 ? file.find_last_of('.', e1 - 1) : std::string::npos;
            if (e2 == std::string::npos) error(io, a, "no -S <stage> and no stage extension", file.c_str());
            name = file.substr(e2 + 1, e1 - e2 - 1);
        } else name = ext;
    }
    static const struct { const char *n; EShLanguage l; } t[] = {
        {"vert", EShLangVertex}, {"tesc", EShLangTessControl}, {"tese", EShLangTessEvaluation}, {"geom", EShLangGeometry}, {"frag", EShLangFragment},
        {"comp", EShLangCompute}, {"rgen", EShLangRayGen}, {"rint", EShLangIntersect}, {"rahit", EShLangAnyHit}, {"rchit", EShLangClosestHit},
        {"rmiss", EShLangMiss}, {"rcall", EShLangCallable}, {"mesh", EShLangMesh}, {"task", EShLangTask}};
    for (const auto &x : t) if (name == x.n) return x.l;
    error(io, a, "unknown stage", name.c_str());
}

const char *default_binary_name(EShLanguage s)   /* GetBinaryName without -o */
{
    switch (s) {
    case EShLangVertex: return "vert.spv";          case EShLangTessControl: return "tesc.spv";   case EShLangTessEvaluation: return "tese.spv";
    case EShLangGeometry: return "geom.spv";        case EShLangFragment: return "frag.spv";      case EShLangCompute: return "comp.spv";
    case EShLangRayGen: return "rgen.spv";          case EShLangIntersect: return "rint.spv";     case EShLangAnyHit: return "rahit.spv";
    case EShLangClosestHit: return "rchit.spv";     case EShLangMiss: return "rmiss.spv";         case EShLangCallable: return "rcall.spv";
    case EShLangMesh: return "mesh.spv";            case EShLangTask: return "task.spv";          default: return "unknown";
    }
}

std::string read_file(Io &io, const Args &a, const char *path)   /* ReadFileData: the bytes, a UTF-8 BOM skipped, up to the first NUL (the text is passed by strlen) */
{
    FILE *f = fopen(path, "r");
    if (!f) error(io, a, "unable to open input file");
    std::string s;
    char buf[65536];
    size_t n;
    while ((n = fread(buf, 1, sizeof buf, f)) > 0) s.append(buf, n);
    bool bad = ferror(f) != 0;
    fclose(f);
    if (bad) error(io, a, "can't read input file");
    if (s.size() > 3 && (unsigned char)s[0] == 0xef && (unsigned char)s[1] == 0xbb && (unsigned char)s[2] == 0xbf) s.erase(0, 3);
    size_t z = s.find('\0');
    if (z != std::string::npos) s.resize(z);
    return s;
}

void dump_object(Io &io, const glslang::TObjectReflection &o)   /* TObjectReflection::dump */
{
    io.printf_out("%s: offset %d, type %x, size %d, index %d, binding %d, stages %d", o.name.c_str(), o.offset, (unsigned)o.glDefineType, o.size, o.index,
                  o.getBinding(), (int)o.stages);
    if (o.counterIndex != -1) io.printf_out(", counter %d", o.counterIndex);
    if (o.numMembers != -1) io.printf_out(", numMembers %d", o.numMembers);
    if (o.arrayStride != 0) io.printf_out(", arrayStride %d", o.arrayStride);
    if (o.topLevelArrayStride != 0) io.printf_out(", topLevelArrayStride %d", o.topLevelArrayStride);
    io.printf_out("\n");
}

void dump_reflection(Io &io, const glslang::TProgram &p)   /* TReflection::dump, through TProgram's accessors */
{
    io.printf_out("Uniform reflection:\n");
    for (int i = 0; i < p.getNumUniformVariables(); ++i) dump_object(io, p.getUniform(i));
    io.printf_out("\nUniform block reflection:\n");
    for (int i = 0; i < p.getNumUniformBlocks(); ++i) dump_object(io, p.getUniformBlock(i));
    io.printf_out("\nBuffer variable reflection:\n");
    for (int i = 0; i < p.getNumBufferVariables(); ++i) dump_object(io, p.getBufferVariable(i));
    io.printf_out("\nBuffer block reflection:\n");
    for (int i = 0; i < p.getNumBufferBlocks(); ++i) dump_object(io, p.getBufferBlock(i));
    io.printf_out("\nPipeline input reflection:\n");
    for (int i = 0; i < p.getNumPipeInputs(); ++i) dump_object(io, p.getPipeInput(i));
    io.printf_out("\nPipeline output reflection:\n");
    for (int i = 0; i < p.getNumPipeOutputs(); ++i) dump_object(io, p.getPipeOutput(i));
    io.printf_out("\n");
    static const char *axis[] = {"X", "Y", "Z"};
    if (p.getLocalSize(0) > 1) {
        for (int d = 0; d < 3; ++d)
            if (p.getLocalSize(d) > 1) io.printf_out("Local size %s: %u\n", axis[d], p.getLocalSize(d));
        io.printf_out("\n");
    }
    if (p.getTileShadingRateQCOM(0) > 1 || p.getTileShadingRateQCOM(1) > 1) {
        for (int d = 0; d < 3; ++d) io.printf_out("Tile shading rate QCOM %s: %u\n", axis[d], p.getTileShadingRateQCOM(d));
        io.printf_out("\n");
    }
}

void print_versions(Io &io)   /* singleMain, EOptionDumpVersions */
{
    int gen = glslang::GetSpirvGeneratorVersion();
    io.printf_out("Glslang Version: %d:%d.%d.%d%s\n", gen, GLSLANG_VERSION_MAJOR, GLSLANG_VERSION_MINOR, GLSLANG_VERSION_PATCH, GLSLANG_VERSION_FLAVOR);
    io.printf_out("ESSL Version: %s\n", glslang::GetEsslVersionString());
    io.printf_out("GLSL Version: %s\n", glslang::GetGlslVersionString());
    std::string spirv;
    glslang::GetSpirvVersion(spirv);
    io.printf_out("SPIR-V Version %s\n", spirv.c_str());
    io.printf_out("GLSL.std.450 Version %d, Revision %d\n", GLSLstd450Version, GLSLstd450Revision);
    io.printf_out("Khronos Tool ID %d\n", glslang::GetKhronosToolId());
    io.printf_out("SPIR-V Generator Version %d\n", gen);
    io.printf_out("GL_KHR_vulkan_glsl version %d\n", 100);
    io.printf_out("ARB_GL_gl_spirv version %d\n", 100);
}

std::once_flag g_init;

/* CompileAndLinkShaderUnits for one file; returns the exit code */
int compile(Io &io, const Args &a)
{
    const std::string &file = a.files[0];
    EShLanguage stage = stage_of(io, a, file);
    std::string text = read_file(io, a, file.c_str());
    std::call_once(g_init, [] { glslang::InitializeProcess(); });

    EShMessages messages = EShMsgDefault;   /* SetMessageOptions */
    if (a.spv) messages = (EShMessages)(messages | EShMsgSpvRules);
    if (a.vulkan) messages = (EShMessages)(messages | EShMsgVulkanRules);
    if (a.preprocess) messages = (EShMessages)(messages | EShMsgOnlyPreprocessor);

    DirStackFileIncluder includer;
    bool compile_failed = false, link_failed = false;
    const char *texts[1] = {text.c_str()}, *names[1] = {file.c_str()};
    glslang::TShader shader(stage);   /* before the program: the program goes first (it may hold what it merged from the shader) */
    shader.setStringsWithLengthsAndNames(texts, nullptr, names, 1);
    shader.setOverrideVersion(0);
    std::string preamble = getIntrinsic(texts, 1);
    shader.setPreamble(preamble.c_str());
    for (int r = 0; r < glslang::EResCount; ++r) shader.setShiftBinding(glslang::TResourceType(r), 0);
    shader.setNoStorageFormat(false);
    shader.setResourceSetBinding(std::vector<std::string>());
    if (a.amb) shader.setAutoMapBindings(true);
    if (a.aml) shader.setAutoMapLocations(true);
    shader.setUniformLocationBase(0);
    shader.setNanMinMaxClamp(false);
    if (a.spv) {
        shader.setEnvInput(glslang::EShSourceGlsl, stage, glslang::EShClientVulkan, 100);
        shader.setEnvClient(glslang::EShClientVulkan, glslang::EShTargetVulkan_1_0);
        shader.setEnvTarget(glslang::EShTargetSpv, glslang::EShTargetSpv_1_0);
        if (a.relaxed_rules) shader.setEnvInputVulkanRulesRelaxed();
    }
    const TBuiltInResource *res = GetDefaultResources();
    const int default_version = 100;

    if (a.preprocess) {
        std::string str;
        if (shader.preprocess(res, default_version, ENoProfile, false, false, messages, &str, includer)) io.puts_if_non_empty(str.c_str());
        else compile_failed = true;
        io.stderr_if_non_empty(shader.getInfoLog());
        io.stderr_if_non_empty(shader.getInfoDebugLog());
        return compile_failed ? EFailCompile : ESuccess;
    }

    glslang::TProgram program;
    if (!shader.parse(res, default_version, false, messages, includer)) compile_failed = true;
    program.addShader(&shader);
    if (!a.quiet) io.stderr_if_non_empty(file.c_str());
    io.stderr_if_non_empty(shader.getInfoLog());
    io.stderr_if_non_empty(shader.getInfoDebugLog());

    if (!program.link(messages)) link_failed = true;
    if (a.spv && !program.mapIO()) link_failed = true;
    io.stderr_if_non_empty(program.getInfoLog());
    io.stderr_if_non_empty(program.getInfoDebugLog());
    if (a.reflect) {
        program.buildReflection(EShReflectionDefault);
        dump_reflection(io, program);   /* the program was linked: its reflection exists (TProgram::dumpReflection's test) */
    }

    if (a.spv) {
        if (compile_failed || link_failed) io.printf_out("SPIR-V is not generated for failed compile or link\n");
        else {
            for (int s = 0; s < EShLangCount; ++s) {
                glslang::TIntermediate *im = program.getIntermediate((EShLanguage)s);
                if (!im) continue;
                std::vector<unsigned int> spirv;
                spv::SpvBuildLogger logger;
                glslang::SpvOptions o;
                o.disableOptimizer = false;
                o.optimizeSize = false;
                o.optimizePerformance = false;
                o.disassemble = false;
                o.validate = false;
                o.compileOnly = false;
                o.compilerSignature = "glslang";
                o.commandLineArguments = a.command_line.c_str();
                std::error_code ec;
                const std::string cwd = std::filesystem::current_path(ec).string();
                if (!ec) o.currentWorkingDirectory = cwd.c_str();
                glslang::GlslangToSpv(*im, spirv, &logger, &o);
                io.printf_out("%s", logger.getAllMessages().c_str());
                const char *name = a.binary ? a.binary : default_binary_name((EShLanguage)s);
                FILE *f = fopen(name, "wb");   /* OutputSpvBin: the words as they are in memory */
                bool ok = f && fwrite(spirv.data(), sizeof(unsigned int), spirv.size(), f) == spirv.size();
                if (f && fclose(f) != 0) ok = false;
                if (!ok) {
                    io.printf_out("ERROR: Failed to open file: %s\n", name);
                    return EFailUsage;
                }
            }
        }
    }
    if (compile_failed) return EFailCompile;
    if (link_failed) return EFailLink;
    return ESuccess;
}

int run(Io &io, int argc, const char **argv)
{
    Args a;
    parse(io, a, argc, argv);
    if (a.versions) {
        print_versions(io);
        if (a.files.empty()) return ESuccess;
    }
    if (a.files.empty()) error(io, a, "no input file (this build has no usage text)");
    if (a.files.size() > 1) error(io, a, "one input file at a time in this build", a.files[1].c_str());
    if (!a.link && !a.preprocess) error(io, a, "only -E or -V (linking) is supported by this build");
    return compile(io, a);
}

char *dup_c(const std::string &s)
{
    char *p = (char *)malloc(s.size() + 1);
    if (p) memcpy(p, s.c_str(), s.size() + 1);
    return p;
}

}   // namespace

extern "C" int gameapp_glslang(int argc, const char **argv, char **out_stdout, char **out_stderr)
{
    if (out_stdout) *out_stdout = nullptr;
    if (out_stderr) *out_stderr = nullptr;
    int rc;
    Io io;
    try {
        try {
            rc = run(io, argc, argv);
        } catch (const Usage &) {
            rc = EFailUsage;
        }
        char *o = out_stdout ? dup_c(io.out) : nullptr, *e = out_stderr ? dup_c(io.err) : nullptr;
        if ((out_stdout && !o) || (out_stderr && !e)) { free(o); free(e); return EFailUsage; }
        if (out_stdout) *out_stdout = o;
        if (out_stderr) *out_stderr = e;
        return rc;
    } catch (const std::bad_alloc &) {
        if (out_stderr) *out_stderr = dup_c("out of memory");
        return EFailUsage;
    } catch (...) {
        if (out_stderr) *out_stderr = dup_c("glslang: an unexpected C++ exception");
        return EFailUsage;
    }
}

#ifdef GAMEAPP_GLSLANG_MAIN
int main(int argc, char **argv)
{
    char *o = nullptr, *e = nullptr;
    int rc = gameapp_glslang(argc, (const char **)argv, &o, &e);
    if (o) { fputs(o, stdout); free(o); }
    if (e) { fputs(e, stderr); free(e); }
    return rc;
}
#endif
