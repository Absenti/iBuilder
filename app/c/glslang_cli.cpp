/*
 * glslang_cli.cpp: the engine's `glslangValidator` command line, in process.
 *
 *   extern "C" int gameapp_glslang(int argc, const char **argv, char **out_stdout, char **out_stderr);
 *
 * argv[0] is the program name, as in main(). The function takes exactly the subset of glslangValidator's command line the OpenGL port uses
 * (dm/gfx/tools/gl_shaders.py, ported in crates/ibuilder-glvk/src/gl.rs) and drives glslang's C++ API (release 16.6.0, scripts/build-glslang.sh) as
 * StandAlone/StandAlone.cpp of that release does for the same flags, so its outputs are the tool's: the same SPIR-V file, and on stdout / stderr the same
 * text (the port reads the preprocessed text after "#version", the reflection, and the ERROR lines). crates/ibuilder-glvk/tests/gl_oracle.rs passes with
 * this wrapper built for the Mac (GLSLANG=<target/glslang/mac/glslang-cli>) as with Homebrew's glslangValidator 16.6.0.
 *
 * Supported:   -E -S <stage> <file>                                  preprocess to stdout (EShMsgOnlyPreprocessor)
 *              -V -R --aml --amb -q -S <stage> <file> -o <spv>         Vulkan 1.0 / SPIR-V 1.0 rules, relaxed (setEnvInputVulkanRulesRelaxed), locations and
 *                                                                     bindings auto-mapped, link, mapIO, the reflection of TReflection::dump on stdout
 *                                                                     (built from TProgram's getNumUniformVariables / getUniform / getUniformBlock ...),
 *                                                                     GlslangToSpv into <spv>
 *              --version (-v)                                         the version block, as the tool prints it
 *              the synonyms the tool knows for these (--auto-map-locations, --auto-map-bindings, --auto-map-binding, -V100), --quiet, and the order is free.
 *              Any other flag is not guessed at: exit code 1 (the tool's EFailUsage) and a message on stderr. The tool's old non-linking path (no -E, no -V/-l) is
 *              not here either (exit code 1).
 * Results: the tool's exit codes, 0 ok, 1 usage (also a file that cannot be read or written), 2 compile failed, 3 link failed. *out_stdout / *out_stderr get what
 * the tool prints on stdout / stderr, as NUL-terminated malloc'd strings (empty, never NULL) the caller frees; either pointer may be NULL. No memory: exit code 1
 * and NULL outputs, never a truncated text. Each call has its own TShader / TProgram; glslang::InitializeProcess runs once per process (std::call_once) and is
 * never finalized, so concurrent calls from the build's worker threads are safe (glslang keeps its pool per thread and guards its shared symbol tables).
 * No process is started, no stdin is read.
 *
 * Build: -std=c++17 -I<target/glslang/include> -I<...>/include/glslang, link libglslang-<ios|sim|mac>.a (scripts/build-glslang.sh) and -lc++.
 * -DGAMEAPP_GLSLANG_MAIN adds a main() that prints the two texts and returns the code: the Mac CLI of the proof (scripts/build-glslang.sh mac).
 * Licences: glslang is BSD-3-Clause / BSD-2-Clause / MIT / Apache-2.0 (and its preprocessor NVIDIA's AML-glslang notice, its grammar Bison output, GPL-3.0-or-later
 * WITH Bison-exception-2.2, which allows this binary distribution): NOTICE.md (section 3). DirStackFileIncluder.h is glslang's own (BSD-3-Clause).
 */
