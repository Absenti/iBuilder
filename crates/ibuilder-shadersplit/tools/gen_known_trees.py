#!/usr/bin/env python3
"""Writes src/unity_trees.rs: the type-tree layouts of `unityfs.KNOWN_TREES` (the engine's `dm/gfx/tools/unityfs.py`), as Rust string constants.
Usage: PYTHONDONTWRITEBYTECODE=1 python3 -I gen_known_trees.py <engine dm/gfx/tools dir> > src/unity_trees.rs
The layouts are text the Python builds with `+` and `.replace`, so the generator imports the module and writes what it computed (nothing is retyped)."""
import sys, importlib.util
tools = sys.argv[1]
spec = importlib.util.spec_from_file_location('unityfs', tools + '/unityfs.py')
u = importlib.util.module_from_spec(spec); spec.loader.exec_module(u)
print('//! GENERATED by tools/gen_known_trees.py from the engine\'s dm/gfx/tools/unityfs.py (KNOWN_TREES): the Shader and ComputeShader type-tree layouts')
print('//! a game with stripped serialized files borrows, by (class ID, type hash). Do not edit by hand.\n')
print('/// (class ID, type hash, root type, layout)')
print('pub const KNOWN_TREES: &[(i32, [u8; 16], &str, &str)] = &[')
for (cid, h), (root, layout) in u.KNOWN_TREES.items():
    assert '"####' not in layout
    print(f'    ({cid}, [{", ".join(f"{b:#04x}" for b in h)}], "{root}", r####"{layout}"####),')
print('];')
