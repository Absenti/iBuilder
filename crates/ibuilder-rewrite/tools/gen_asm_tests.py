# Generates crates/ibuilder-a64/src/asm/tests.rs from the Python nso_asm (the oracle encoders).
import os, sys, random
def need(name):   # a setting of this machine's fixtures: the environment (source scripts/local.env first; see scripts/local.env.example)
    v = os.environ.get(name)
    if not v: sys.exit(f'{name} is not set (see scripts/local.env.example)')
    return v
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, need('IBUILDER_SCRATCH_OLD') + '/ref/engine/dm/tools')   # a copy of the engine's Python tools
import nso_asm as A
random.seed(7)
lines = []
def case(name, args, val, ok=True):
    lines.append((name, args, val))
regs = [0, 1, 7, 15, 16, 17, 18, 29, 30, 31]
out = ['// Generated by crates/ibuilder-rewrite/tools/gen_asm_tests.py from dm/tools/nso_asm.py (Python): expected words are the oracle\'s.', 'use super::*;', '']
out.append('#[test]\nfn encoders_match_python() {')
def emit(expr, val): out.append(f'    assert_eq!({expr}, {val:#010x}u32);')
for frm, to in [(0, 4), (0x1000, 0), (-0xc60000, 0x1234), (0x7000000, -0xc60000 + 8), (0x100, 0x100 + (1 << 27) - 4), (0x100, 0x100 - (1 << 27)), (-0x20, -0x1c), (12345 * 4, 98765 * 4)]:
    emit(f'b({frm}, {to}).unwrap()', A.B(frm, to)); emit(f'bl({frm}, {to}).unwrap()', A.BL(frm, to))
for frm, to in [(0, 4), (0x1000, 0), (-0xc60000, -0xc60000 + 0xfffc0), (0x100, 0x100 + (1 << 20) - 4), (0x100, 0x100 - (1 << 20))]:
    emit(f'beq({frm}, {to}).unwrap()', A.BEQ(frm, to))
    for t in (0, 5, 30): emit(f'cbnzw({t}, {frm}, {to}).unwrap()', A.CBNZW(t, frm, to))
for t, t2, n, off in [(0, 1, 31, -16), (16, 17, 31, 16), (29, 30, 31, -16), (3, 9, 31, -112), (5, 6, 31, 0), (2, 3, 4, 504), (15, 16, 31, -24 - 8), (1, 2, 31, -512)]:
    for nm, f in (('stp', A.STP), ('ldp', A.LDP), ('stp_pre', A.STP_PRE), ('ldp_post', A.LDP_POST)):
        emit(f'{nm}({t}, {t2}, {n}, {off})', f(t, t2, n, off))
for t, n, off in [(16, 31, -16), (17, 31, -24), (15, 31, -24), (0, 31, 0), (2, 3, 255), (2, 3, -256), (30, 31, -8)]:
    emit(f'stur({t}, {n}, {off})', A.STUR(t, n, off)); emit(f'ldur({t}, {n}, {off})', A.LDUR(t, n, off))
for t, n, imm in [(0, 0, 0), (16, 16, 0), (15, 16, 3), (3, 4, 508), (3, 4, 511)]:
    emit(f'ldrx({t}, {n}, {imm})', A.LDRX(t, n, imm)); emit(f'strx({t}, {n}, {imm})', A.STRX(t, n, imm))
for d, m in [(0, 1), (19, 15), (1, 18)]: emit(f'movx({d}, {m})', A.MOVX(d, m))
for t in regs: emit(f'mrs_tpidrro({t})', A.MRS_TPIDRRO(t)); emit(f'br({t})', A.BR(t)); emit(f'blr({t})', A.BLR(t))
for d, pc, tg in [(1, 0, 0x4000), (2, 0x1000, 0x0), (17, -0xc60000, 0xa204000), (5, -0xc5f000, 0xa204000), (3, 0x123456, 0x123456), (4, 0x7000000, 0xfff), (4, 0x1ff4, -0x2000)]:
    emit(f'adrp({d}, {pc}, {tg}).unwrap()', A.ADRP(d, pc, tg))
for d, n, imm, sh in [(1, 2, 0, 0), (16, 16, 0xFFF, 0), (16, 16, 0xFFF, 1), (17, 17, 0x123, 0), (31, 31, 15, 0)]:
    emit(f'addi({d}, {n}, {imm}, {sh})', A.ADDI(d, n, imm, sh)); emit(f'subi({d}, {n}, {imm}, {sh})', A.SUBI(d, n, imm, sh))
for d, n, m in [(1, 2, 3), (16, 16, 17), (3, 3, 18)]: emit(f'addr({d}, {n}, {m})', A.ADDR(d, n, m))
for n, m in [(16, 17), (1, 2)]: emit(f'cmpr({n}, {m})', A.CMPR(n, m))
for imm in (0x18, 0, 0xFFFF): emit(f'brk({imm})', A.BRK(imm))
emit('NOP', A.NOP)
out.append('}')
# the asserts
out.append('')
out.append('#[test]\nfn reach_asserts_like_python() {')
for fn, args in [('b', (0, 1 << 27)), ('b', (0, 2)), ('b', (0, -(1 << 27) - 4)), ('beq', (0, 1 << 20)), ('beq', (0, -(1 << 20) - 4)), ('cbnzw', (0, 0, 1 << 20)), ('adrp', (1, 0, 1 << 32)), ('adrp', (1, 0, -(1 << 32) - 0x1000))]:
    f = {'b': A.B, 'beq': A.BEQ, 'cbnzw': A.CBNZW, 'adrp': A.ADRP}[fn]
    try: f(*args); res = 'ok'
    except AssertionError: res = 'err'
    a = ', '.join(str(x) for x in args)
    out.append(f'    assert_eq!({fn}({a}).is_err(), {"true" if res == "err" else "false"});')
out.append('}')
dest = os.path.normpath(os.path.join(HERE, '..', '..', 'ibuilder-a64', 'src', 'asm'))
os.makedirs(dest, exist_ok=True)
open(dest + '/tests.rs', 'w').write('\n'.join(out) + '\n')
print(len(out), 'lines')
