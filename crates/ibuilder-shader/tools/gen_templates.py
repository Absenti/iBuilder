#!/usr/bin/env python3
"""Generates src/templates.rs: the fixed MSL text the engine's rewrites insert (dmsh_rewrite.py, dmsh_entry.py, dmsh_geometry.py), taken from the engine's own
Python so that no template is retyped by hand.   usage: gen_templates.py <engine dir (the one holding dm/)>  > src/templates.rs
Run with PYTHONDONTWRITEBYTECODE=1 and a copy of the engine (the engine tree itself is read-only)."""
import os, sys
eng = sys.argv[1]
sys.path.insert(0, os.path.join(eng, 'dm/gfx/tools')); sys.path.insert(0, os.path.join(eng, 'dm/tools'))
import dmsh_rewrite as rw, dmsh_abi as abi, dmsh_geometry as geo, dmsh_entry as en, dmsh_side as sd, dmsh_reflect as rf

out = ['// GENERATED by tools/gen_templates.py from the engine\'s dmsh_*.py (do not edit): the fixed MSL text of the chain\'s rewrites.\n']
def const(name, text):
    h = '#' * 6
    assert '"' + h not in text
    out.append(f'pub const {name}: &str = r{h}"{text}"{h};\n')
const('BORDER_HELPERS', rw.BORDER_HELPERS)
const('BORDER_LIVE_FC', rw.BORDER_LIVE_FC)
const('ZSNAP', rw.ZSNAP)
const('UWORD', rw.UWORD)
const('TG_FENCE', rw.TG_FENCE)
# membar_fence's texts: the engine's chain no longer has the step (SPIRV-Cross writes the fences at MSL 3.2); kept as they were for steps::membar_fence until no caller is left
const('MEMBAR', 'threadgroup_barrier(mem_flags::mem_device | mem_flags::mem_threadgroup | mem_flags::mem_texture);')
const('MEMBAR_FENCE', 'atomic_thread_fence(mem_flags::mem_device | mem_flags::mem_threadgroup | mem_flags::mem_texture, memory_order_seq_cst, thread_scope_device);   // MEMBAR (membar_fence)')
const('BLEND_ZERO_PARAM', rw.BLEND_ZERO_PARAM)
bits, rb = abi.BLEND_ZERO_BITS, abi.BLEND_ROUND_BITS
full = rw.BLEND_ZERO % ((1 << bits) - 1, (1 << rb) - 1, abi.ROUND_8, abi.ROUND_16, '@@COLS@@')
pre, post = full.split('@@COLS@@')
const('BLEND_ZERO_PRE', pre); const('BLEND_ZERO_POST', post)
out.append(f'pub const BLEND_ZERO_BITS: u32 = {bits};\npub const BLEND_ROUND_BITS: u32 = {rb};\n')
out.append(f'pub const UINT_FC: u32 = {abi.UINT_FC};\npub const TG_MAX: u32 = {abi.TG_MAX};\npub const CBSIZE_BANK: u32 = {abi.CBSIZE_BANK};\npub const SBLEN_BANK: u32 = {abi.SBLEN_BANK};\n')
out.append(f'pub const BORDER_SAMPLERS: usize = {abi.BORDER_SAMPLERS};\npub const BORDER_FC: u32 = {abi.BORDER_FC};\npub const CAPTURE_SLOT: u32 = {geo.CAPTURE_SLOT};\npub const CAPTURE_WORDS: usize = {geo.WORDS};\n')
const('BODY', sd.BODY)
# F1 round: the texts of the steps ported after the first release (hmma, pools, gathers, shared stores, threadgroup spill)
out.append(f'pub const TG_SLOT: u32 = {abi.TG_SLOT};\npub const POOL_MIN: u32 = {rf.POOL_MIN};\n')
const('POOL_MARK', rf.POOL_MARK)
const('SHARED_ALIAS', rw.SHARED_ALIAS)
const('GATHER4', rw.GATHER4)
const('HMMA_BODY', rw.HMMA_BODY)
# compute loop containment (compute_loops), raw_noinline, the buffer texture pools (pool_arrays)
out.append(f'pub const LOOP_SLOT: u32 = {abi.LOOP_SLOT};\npub const LOOP_CAP: u32 = {rw.LOOP_CAP};\npub const LOOP_ABORT_EVERY: u32 = {rw.LOOP_ABORT_EVERY};\n')
# the helper compute_loops inserts after `using namespace metal;`, taken from its output for a one-loop kernel
probe = 'using namespace metal;\nkernel void main0()\n{\n    for (;;)\n    {\n    }\n}\n'
head = 'using namespace metal;\n'
looped = rw.compute_loops(probe)[0]
assert looped.startswith(head)
const('LOOP_HELPER', looped[len(head):looped.index('kernel void main0(')])
const('BUFFER_POOL_READ', rf.BUFFER_POOL_READ)
out.append('pub const HMMA_ARGS: [&str; %d] = [%s];\n' % (len(rw.HMMA_ARGS), ', '.join('"%s"' % a for a in rw.HMMA_ARGS)))
sys.stdout.write(''.join(out))
