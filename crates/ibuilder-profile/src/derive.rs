//! `gameapp/profile_derive.py`: derive the per-game runtime profile (`profile.tsv`) from the game's own files.
//!
//! Two paths, exactly as the Python has them:
//! * the game is one of the registered ones (`<bundle>/dm/games/<title ID>/game.tsv` exists): the engine's own
//!   generator renders that table ([`crate::game::write_profile`]);
//! * it is not: a **provisional** `game.tsv` is derived from the extraction (`facts_of` + `guess`, the port of
//!   `build_ipa_from_nsp.py write_profile`) and rendered by the same generator.
use crate::error::{Error, Result};
use crate::facts::{Facts, facts_of};
use crate::game::{Game, find_dir, write_profile};
use crate::guess::{Guess, guess};
use crate::nacp;
use crate::syms::HookSet;
use std::path::{Path, PathBuf};

/// `ipa_name(name, app)`: "The Legend of Zelda: Link's Awakening" -> TheLegendOfZeldaLinksAwakening.ipa
pub fn ipa_name(name: &str, app: u64) -> String {
    let cleaned = name.replace(['\'', '\u{2019}'], "");
    let mut words: Vec<String> = Vec::new();
    let mut cur = String::new();
    for c in cleaned.chars() {
        if c.is_ascii_alphanumeric() {
            cur.push(c);
        } else if !cur.is_empty() {
            words.push(std::mem::take(&mut cur));
        }
    }
    if !cur.is_empty() {
        words.push(cur);
    }
    let words: Vec<String> = words
        .into_iter()
        .map(|w| {
            let cased = w.chars().any(|c| c.is_ascii_alphabetic());
            let upper = cased && !w.chars().any(|c| c.is_ascii_lowercase());
            if upper && w.chars().count() > 1 {
                // str.capitalize(): first upper, the rest lower
                let mut cs = w.chars();
                let f = cs.next().unwrap().to_ascii_uppercase();
                format!("{f}{}", cs.as_str().to_ascii_lowercase())
            } else {
                let mut cs = w.chars();
                let f = cs
                    .next()
                    .map(|c| c.to_ascii_uppercase().to_string())
                    .unwrap_or_default();
                format!("{f}{}", cs.as_str())
            }
        })
        .collect();
    let joined: String = words.concat().chars().take(48).collect();
    format!(
        "{}.ipa",
        if joined.is_empty() {
            format!("{app:016X}")
        } else {
            joined
        }
    )
}

