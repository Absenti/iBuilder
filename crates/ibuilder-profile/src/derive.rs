/// The application title ID: nx_extract's own `RomFS.img.id` (its `title`), else `main.npdm`'s program ID.
pub fn title_id(extract: &Path, exefs: &Path) -> Result<u64> {
    let ident = extract.join("RomFS.img.id");
    if ident.is_file()
        && let Ok(text) = std::fs::read_to_string(&ident)
        && let Some(t) = json_top_level_string(&text, "title")
        && !t.is_empty()
    {
        let t = t.trim();
        let t = t
            .strip_prefix("0x")
            .or_else(|| t.strip_prefix("0X"))
            .unwrap_or(t);
        if let Ok(v) = u64::from_str_radix(&t.replace('_', ""), 16) {
            return Ok(v);
        }
    }
    let npdm = exefs.join("main.npdm");
    if npdm.is_file() {
        let d = std::fs::read(&npdm)?;
        if let Some(a) = crate::search::find(&d, b"ACI0", 0) {
            let b = d
                .get(a + 0x10..a + 0x18)
                .ok_or_else(|| Error::Format("main.npdm is cut short".into()))?;
            return Ok(u64::from_le_bytes(b.try_into().unwrap()));
        }
    }
    Err(Error::Format(format!(
        "no RomFS.img.id and no main.npdm in {}: cannot identify the game",
        extract.display()
    )))
}

/// The value of a top-level string member of a JSON object (`json.loads(text).get(key)`); `None` for anything
/// else (invalid JSON, not an object, other type) like the Python's `except ValueError`.
fn json_top_level_string(text: &str, key: &str) -> Option<String> {
    let b = text.as_bytes();
    let mut i = 0;
    let ws = |i: &mut usize| {
        while *i < b.len() && matches!(b[*i], b' ' | b'\t' | b'\n' | b'\r') {
            *i += 1;
        }
    };
    fn string(b: &[u8], i: &mut usize) -> Option<String> {
        if b.get(*i) != Some(&b'"') {
            return None;
        }
        *i += 1;
        let mut out: Vec<u8> = Vec::new();
        while *i < b.len() {
            match b[*i] {
                b'"' => {
                    *i += 1;
                    return String::from_utf8(out).ok();
                }
                b'\\' => {
                    *i += 1;
                    let e = *b.get(*i)?;
                    *i += 1;
                    match e {
                        b'"' | b'\\' | b'/' => out.push(e),
                        b'n' => out.push(b'\n'),
                        b't' => out.push(b'\t'),
                        b'r' => out.push(b'\r'),
                        b'b' => out.push(8),
                        b'f' => out.push(12),
                        b'u' => {
                            let h = std::str::from_utf8(b.get(*i..*i + 4)?).ok()?;
                            let c = char::from_u32(u32::from_str_radix(h, 16).ok()?)
                                .unwrap_or('\u{fffd}');
                            *i += 4;
                            out.extend_from_slice(c.to_string().as_bytes());
                        }
                        _ => return None,
                    }
                }
                c => {
                    out.push(c);
                    *i += 1;
                }
            }
        }
        None
    }
    // skip any value (string, number, literal, nested object/array)
    fn skip(b: &[u8], i: &mut usize) -> Option<()> {
        match *b.get(*i)? {
            b'"' => string(b, i).map(|_| ()),
            b'{' | b'[' => {
                let mut depth = 0;
                while *i < b.len() {
                    match b[*i] {
                        b'"' => {
                            string(b, i)?;
                            continue;
                        }
                        b'{' | b'[' => depth += 1,
                        b'}' | b']' => {
                            depth -= 1;
                            if depth == 0 {
                                *i += 1;
                                return Some(());
                            }
                        }
                        _ => {}
                    }
                    *i += 1;
                }
                None
            }
            _ => {
                while *i < b.len() && !matches!(b[*i], b',' | b'}' | b']') {
                    *i += 1;
                }
                Some(())
            }
        }
    }
    ws(&mut i);
    if b.get(i) != Some(&b'{') {
        return None;
    }
    i += 1;
    loop {
        ws(&mut i);
        if b.get(i) == Some(&b'}') {
            return None;
        }
        let k = string(b, &mut i)?;
        ws(&mut i);
        if b.get(i) != Some(&b':') {
            return None;
        }
        i += 1;
        ws(&mut i);
        if k == key {
            return string(b, &mut i);
        }
        skip(b, &mut i)?;
        ws(&mut i);
        match b.get(i) {
            Some(b',') => i += 1,
            _ => return None,
        }
    }
}

/// Everything `derive` takes (`cfg` in the Python plus the bundle it runs from).
#[derive(Clone, Debug)]
pub struct DeriveConfig {
    /// `<Documents>/extract`
    pub extract_out: PathBuf,
    /// default `<extract>/ExeFS`
    pub exe_dir: Option<PathBuf>,
    /// RomFS.img, a `romfs_manifest.tsv`, or a RomFS folder; default `<extract>/RomFS.img`
    pub romfs: Option<PathBuf>,
    /// output `profile.tsv`; default `<extract>/../profile.tsv`
    pub profile: Option<PathBuf>,
    /// folder of the provisional `game.tsv` (`<id>/` inside it); default `<extract>/../profile-derived/<id>`
    pub profile_out: Option<PathBuf>,
    pub version: String,
    /// The engine bundle (`<bundle>/dm/games`, `<bundle>/dm/host`): `GAMEAPP_BUNDLE`.
    pub bundle: PathBuf,
    /// The HLE hook names; `None` reads them from `<bundle>/dm/host` + `dm/gfx`.
    pub hooks: Option<HookSet>,
}

impl DeriveConfig {
    pub fn new(extract_out: impl Into<PathBuf>, bundle: impl Into<PathBuf>) -> Self {
        DeriveConfig {
            extract_out: extract_out.into(),
            exe_dir: None,
            romfs: None,
            profile: None,
            profile_out: None,
            version: "v0".into(),
            bundle: bundle.into(),
            hooks: None,
        }
    }
}

fn parent_of(p: &Path) -> PathBuf {
    p.parent().map(Path::to_path_buf).unwrap_or_default()
}

/// `write_provisional_profile`: the provisional `game.tsv` + the empty tables. Returns `(facts, guess)`.
#[allow(clippy::too_many_arguments)]
pub fn write_provisional_profile(
    pdir: &Path,
    app: u64,
    exefs: &Path,
    romfs: &Path,
    name: &str,
    display: &str,
    version: &str,
    hooks: &HookSet,
    log: &mut dyn FnMut(&str),
) -> Result<(Facts, Guess)> {
    let f = facts_of(exefs, romfs)?;
    let g = guess(&f, hooks)?;
    let r = &f.romfs;
    std::fs::create_dir_all(pdir)?;
    // shader package groups by RomFS top-level folder (write_profile:1203)
    let mut groups: Vec<String> = Vec::new();
    let mut seen: Vec<String> = vec!["main".into(), "other".into()];
    for (d, _) in r.dirs.most_common(24) {
        let lower: String = d
            .to_lowercase()
            .chars()
            .filter(|c| matches!(c, 'a'..='z' | '0'..='9'))
            .collect();
        let mut gname: String = lower.chars().take(16).collect();
        if gname.is_empty() {
            gname = "g".into();
        }
        while seen.contains(&gname) {
            gname.push('x');
        }
        seen.push(gname.clone());
        groups.push(format!("/{d}/={gname}"));
    }
    let mut store: Vec<String> = r
        .extb
        .iter()
        .filter(|(e, b)| {
            !e.is_empty()
                && r.exts.get(e) != 0
                && (*b as u128 >= (r.exts.get(e) as u128) << 20
                    || 2 * r.extc.get(e) >= r.exts.get(e))
        })
        .map(|(e, _)| e.clone())
        .collect();
    store.sort();
    let mods_s = g.get("modules").map(|m| m.0.clone()).unwrap_or_default();
    let mods: Vec<&str> = mods_s.split_whitespace().collect();

    // a key with the reason profile_guess gives it above it (write_profile:1213)
    let key = |k: &str, default: Option<&str>| -> Vec<String> {
        let (v, why): (Option<String>, String) = match g.get(k) {
            Some((v, w)) => (Some(v.clone()), w.clone()),
            None => (default.map(str::to_string), String::new()),
        };
        match v {
            None => vec![],
            Some(v) => {
                let mut o = Vec::new();
                if !why.is_empty() {
                    o.push(format!("# {why}"));
                }
                o.push(format!("{k}\t{v}"));
                o
            }
        }
    };
    let program = f.program.filter(|p| *p != 0).unwrap_or(app);
    let build_row = {
        let mut cols = vec![
            "build".to_string(),
            version.to_string(),
            display.to_string(),
        ];
        for m in &mods {
            let bid = f.module(m).map(|m| m.bid.clone()).unwrap_or_default();
            cols.push(format!("{m}={bid}"));
        }
        cols.join("\t")
    };
    let mut zip_store = store.clone();
    zip_store.push(".metallib".into());
    let mut l: Vec<String> = vec![
        "# Provisional game profile (derived in-process by gameapp/profile_derive.py, the app-side port of".into(),
        "#   scripts/build_ipa_from_nsp.py write_profile with dm/games/profile_guess.py; not checked by hand)".into(),
        format!(
            "# {}, SDK {}, derived from {} + {}",
            name,
            if f.sdk != 0 { f.sdk.to_string() } else { "?".into() },
            exefs.display(),
            romfs.display()
        ),
        String::new(),
        "# ---- Identity ----".into(),
        format!("title_id\t{app:016X}"),
        format!("program_id\t{program:016X}"),
        String::new(),
        "# ---- App ----".into(),
        format!("name\t{name}"),
        format!("ipa\t{}", ipa_name(name, app)),
        "app_category\tpublic.app-category.games".into(),
    ];
    l.extend(key("pad_layout", None));
    l.extend(key("op_mode", None));
    l.push(String::new());
    l.push("# ---- Versions ----".into());
    l.push(build_row);
    l.push(format!("package\t{version}"));
    l.push(format!("shader_versions\t{version}"));
    l.push(String::new());
    l.push("# ---- Files ----".into());
    l.extend(key("modules", None));
    l.push(format!("romfs_marker\t{}", r.biggest.1));
    l.push(format!("zip_store\t{}", zip_store.join(":")));
    l.push(String::new());
    l.push("# ---- Memory ----".into());
    for k in [
        "mem_reserve",
        "mem_alias",
        "mem_stack",
        "app_pool",
        "sys_resource",
    ] {
        l.extend(key(k, None));
    }
    l.push(String::new());
    l.push("# ---- Shader split ----".into());
    let default_groups = if groups.is_empty() {
        "/=romfs".to_string()
    } else {
        groups.join(" ")
    };
    l.extend(key("shader_groups", Some(&default_groups)));
    l.push(format!("shader_note\t{name} shaders"));
    std::fs::write(pdir.join("game.tsv"), l.join("\n") + "\n")?;
    for (n, text) in EMPTY_TABLES {
        std::fs::write(pdir.join(n), text)?;
    }
    log(&format!(
        "  provisional profile written: {}/game.tsv",
        pdir.display()
    ));
    for k in ["modules", "mem_reserve", "op_mode"] {
        if let Some((v, why)) = g.get(k)
            && !why.is_empty()
        {
            log(&format!("    {k} {v}: {why}"));
        }
    }
    Ok((f, g))
}

/// `render(game_id, out_tsv, log)`: `game.py profile <id> <out>`.
fn render(
    game_id: &str,
    games_dir: &Path,
    extra: &[PathBuf],
    first: bool,
    out_tsv: &Path,
    log: &mut dyn FnMut(&str),
) -> Result<PathBuf> {
    let d = find_dir(game_id, games_dir, extra, first);
    if !d.join("game.tsv").exists() {
        return Err(Error::Red(format!(
            "no game profile {} (DM_GAME / GAME take the base game title ID)",
            d.join("game.tsv").display()
        )));
    }
    let g = Game::load_dir(&d)?;
    let (rows, warnings) = write_profile(&g, out_tsv)?;
    for w in warnings {
        eprintln!("{w}");
    }
    log(&out_tsv.display().to_string()); // game.py's own print(out)
    log(&format!(
        "  game.py profile {game_id} -> {} ({rows} rows)",
        out_tsv.display()
    ));
    Ok(out_tsv.to_path_buf())
}

/// `derive(cfg, log)`: derive `<Documents>/profile.tsv` for the game already extracted under `<Documents>/extract`.
pub fn derive(cfg: &DeriveConfig, log: &mut dyn FnMut(&str)) -> Result<PathBuf> {
    let extract = &cfg.extract_out;
    let exefs = cfg.exe_dir.clone().unwrap_or_else(|| extract.join("ExeFS"));
    let romfs = cfg
        .romfs
        .clone()
        .unwrap_or_else(|| extract.join("RomFS.img"));
    let out_tsv = cfg
        .profile
        .clone()
        .unwrap_or_else(|| parent_of(extract).join("profile.tsv"));
    let app = title_id(extract, &exefs)?;
    let nacp_path = extract.join("control.nacp");
    let (mut name, mut display) = (None, None);
    match (nacp::name(&nacp_path), nacp::version(&nacp_path)) {
        (Ok(n), Ok(v)) => {
            name = Some(n).filter(|s| !s.is_empty());
            display = Some(v).filter(|s| !s.is_empty());
        }
        (Err(e), _) | (_, Err(e)) => log(&format!("  control.nacp: {e}")), // a name is nice, not required: the id stands in
    }
    let name = name.unwrap_or_else(|| format!("{app:016X}"));
    let display = display.unwrap_or_else(|| "?".into());

    let games_dir = cfg.bundle.join("dm").join("games");
    let id = format!("{app:016X}");
    let table = games_dir.join(&id).join("game.tsv");
    if table.is_file() {
        // the engine's own table ships in the bundle: the engine's generator renders it as it is
        log(&format!(
            "profile: engine table {} -- game.py profile renders it",
            table.display()
        ));
        log(&format!(
            "  source: dm/games/{id}/game.tsv (registered, not derived)"
        ));
        return render(&id, &games_dir, &[], false, &out_tsv, log);
    }

    // no table: the provisional derivation, into a folder the generator is pointed at
    let pdir = cfg
        .profile_out
        .clone()
        .unwrap_or_else(|| parent_of(extract).join("profile-derived").join(&id));
    if pdir.join("game.tsv").is_file() {
        log(&format!(
            "profile: reusing the provisional table already derived: {}/game.tsv",
            pdir.display()
        ));
    } else {
        log(&format!(
            "profile: no engine table for {id} -- deriving the provisional table"
        ));
        let hooks = match &cfg.hooks {
            Some(h) => h.clone(),
            None => HookSet::from_host_dir(&cfg.bundle.join("dm").join("host"), false)?,
        };
        write_provisional_profile(
            &pdir,
            app,
            &exefs,
            &romfs,
            &name,
            &display,
            &cfg.version,
            &hooks,
            log,
        )?;
    }
    let extra = vec![parent_of(&pdir)];
    render(&id, &games_dir, &extra, true, &out_tsv, log)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ipa() {
        assert_eq!(
            ipa_name("The Legend of Zelda: Link's Awakening", 1),
            "TheLegendOfZeldaLinksAwakening.ipa"
        );
        assert_eq!(
            ipa_name("Grizzy and the Lemmings - Crazy Party", 1),
            "GrizzyAndTheLemmingsCrazyParty.ipa"
        );
        assert_eq!(ipa_name("DRAGON QUEST XI S", 1), "DragonQuestXiS.ipa"); // all-caps words are capitalized, a lone letter is not
        assert_eq!(
            ipa_name("\u{2122}\u{2122}", 0x0100DFA027504000),
            "0100DFA027504000.ipa"
        );
        assert_eq!(
            ipa_name(&"a".repeat(60), 1),
            format!("{}.ipa", "A".to_string() + &"a".repeat(47))
        );
    }

    #[test]
    fn json_title() {
        assert_eq!(
            json_top_level_string(
                "{\"a\": {\"title\": \"x\"}, \"title\": \"0100AB\"}",
                "title"
            )
            .as_deref(),
            Some("0100AB")
        );
        assert_eq!(json_top_level_string("{\"title\": 5}", "title"), None);
        assert_eq!(json_top_level_string("[1]", "title"), None);
    }
}
